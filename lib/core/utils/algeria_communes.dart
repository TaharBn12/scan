/// Communes of one wilaya, in the order the site's dropdown lists them.
List<Commune> communesOf(int wilayaCode) =>
    kAlgeriaCommunes.where((c) => c.wilayaCode == wilayaCode).toList();

/// Looks a commune up by name, ignoring case and diacritics — the order row
/// stores the label, not the id.
Commune? communeByName(String name) {
  final needle = _fold(name);
  if (needle.isEmpty) return null;
  for (final c in kAlgeriaCommunes) {
    if (_fold(c.name) == needle) return c;
  }
  return null;
}

/// Folds a commune name for lookup: lower case, no Arabic diacritics or
/// tatweel, no spaces, hyphens or apostrophes. Double-quoted on purpose — a
/// raw single-quoted Dart string cannot contain its own quote.
String _fold(String raw) => raw
    .toLowerCase()
    .replaceAll(RegExp(r"[\u064B-\u0652\u0640]"), "")
    .replaceAll(RegExp(r"[\s\-\u2019']"), "");
