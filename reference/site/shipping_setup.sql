-- =====================================================
-- جدول تسعير التوصيل (Shipping Rates)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.shipping_rates (
    id SERIAL PRIMARY KEY,
    wilaya_code INTEGER UNIQUE NOT NULL, -- 1 to 58
    wilaya_name TEXT NOT NULL,
    price_home DECIMAL(10, 2) DEFAULT 0, -- توصيل للمنزل
    price_desk DECIMAL(10, 2) DEFAULT 0, -- توصيل للمكتب
    is_active BOOLEAN DEFAULT TRUE,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- تفعيل الحماية
ALTER TABLE public.shipping_rates ENABLE ROW LEVEL SECURITY;

-- الكل يقرأ (لصفحة الهبوط)
CREATE POLICY "Public read shipping" ON public.shipping_rates FOR SELECT USING (true);

-- المدراء فقط يعدلون
CREATE POLICY "Admins manage shipping" ON public.shipping_rates 
    USING (EXISTS (SELECT 1 FROM public.platform_admins WHERE id = auth.uid()))
    WITH CHECK (EXISTS (SELECT 1 FROM public.platform_admins WHERE id = auth.uid()));

